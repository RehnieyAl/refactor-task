const path = require("node:path");

const FRONTEND_DIR = path.resolve(__dirname, "../../frontend");

function readRequired(env, name) {
  const value = env[name]?.trim();
  if (!value) {
    throw new Error(`Falta la variable de entorno obligatoria ${name}.`);
  }
  return value;
}

function parsePort(value) {
  const port = Number(value);
  if (!/^\d+$/.test(value) || port > 65535) {
    throw new Error(`El valor de PORT no es válido: "${value}".`);
  }
  return port;
}

function isHttpOrigin(value) {
  return URL.canParse(value) && ["http:", "https:"].includes(new URL(value).protocol) && new URL(value).origin === value;
}

function parseCorsOrigins(value) {
  const origins = value.split(",").map((origin) => origin.trim()).filter(Boolean);
  const invalidOrigin = origins.find((origin) => !isHttpOrigin(origin));
  if (origins.length === 0 || invalidOrigin !== undefined) {
    throw new Error(`El valor de CORS_ORIGINS no es válido: "${invalidOrigin ?? value}".`);
  }
  return origins;
}

function loadConfig(env) {
  return {
    port: parsePort(readRequired(env, "PORT")),
    corsOrigins: parseCorsOrigins(readRequired(env, "CORS_ORIGINS")),
    frontendDir: FRONTEND_DIR
  };
}

